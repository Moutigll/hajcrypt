/*  ---------- Round primitives - single block ---------- */

/* Middle round: SubBytes + ShiftRows + MixColumns + AddRoundKey */
#define RE(d, rk, r)  (d) = _mm_aesenc_si128((d), (rk)[r])
#define RD(d, rk, r)  (d) = _mm_aesdec_si128((d), (rk)[r])

/* Final round: SubBytes + ShiftRows + AddRoundKey (no MixColumns) */
#define FE(d, rk, nr) (d) = _mm_aesenclast_si128((d), (rk)[nr])
#define FD(d, rk, nr) (d) = _mm_aesdeclast_si128((d), (rk)[nr])

/* Initial AddRoundKey whitening - must be done explicitly before first aesenc/aesdec.
 * Unlike ARM NEON (where vaeseq_u8 XORs the key at the start of each round),
 * AES-NI XORs the key at the END of each round, so the initial whitening
 * with rk[0] must be performed manually before entering the round loop. */
#define W1(d, rk) \
	(d) = _mm_xor_si128((d), (rk)[0])

#define W8(rk) \
	d0 = _mm_xor_si128(d0, (rk)[0]); \
	d1 = _mm_xor_si128(d1, (rk)[0]); \
	d2 = _mm_xor_si128(d2, (rk)[0]); \
	d3 = _mm_xor_si128(d3, (rk)[0]); \
	d4 = _mm_xor_si128(d4, (rk)[0]); \
	d5 = _mm_xor_si128(d5, (rk)[0]); \
	d6 = _mm_xor_si128(d6, (rk)[0]); \
	d7 = _mm_xor_si128(d7, (rk)[0])

static inline __m128i	loadRoundKey(const uint32_t *round_key)
{
	uint8_t	bytes[16];
	int		i;

	i = 0;
	while (i < 4)
	{
		bytes[i * 4 + 0] = (uint8_t)(round_key[i] >> 24);
		bytes[i * 4 + 1] = (uint8_t)(round_key[i] >> 16);
		bytes[i * 4 + 2] = (uint8_t)(round_key[i] >> 8);
		bytes[i * 4 + 3] = (uint8_t)(round_key[i]);
		i++;
	}
	return (_mm_loadu_si128((const __m128i *)bytes));
}

/**
 * @brief Prepare round keys for AES-NI instructions.
 *
 * AES-NI expects round keys in normal order (not reversed like ARM).
 * For decryption, the middle round keys need to be transformed with
 * _mm_aesimc_si128 (Inverse MixColumns).
 *
 * @param rk Output array of round keys (size: AES_MAX_ROUNDS + 1)
 * @param roundKeys Input round keys as generated by the key expansion
 * @param nr Number of rounds (10, 12, or 14)
 * @param encrypt Non-zero for encryption, zero for decryption
 */
__attribute__((target("aes"), always_inline))
static inline void	prepareKeys(__m128i			*rk,
								const uint32_t	*roundKeys,
								int				nr,
								int				encrypt)
{
	__m128i	orig[AES_MAX_ROUNDS + 1];
	int		i;

	i = 0;
	while (i <= nr)
	{
		orig[i] = loadRoundKey(&roundKeys[i * 4]);
		i++;
	}
	if (encrypt)
	{
		i = 0;
		while (i <= nr)
		{
			rk[i] = orig[i];
			i++;
		}
	}
	else
	{
		rk[0] = orig[nr];
		i = 1;
		while (i < nr)
		{
			rk[i] = _mm_aesimc_si128(orig[nr - i]);
			i++;
		}
		rk[nr] = orig[0];
	}
}

