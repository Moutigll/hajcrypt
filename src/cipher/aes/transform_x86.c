/* ---------- Small: generic 8-block function, loop not unrolled ---------- */

__attribute__((target("aes")))
static void	process8BlocksGeneric(const uint8_t		*in,
								  uint8_t			*out,
								  const __m128i		*rk,
								  int				nr,
								  int				encrypt)
{
	__m128i	d0, d1, d2, d3, d4, d5, d6, d7;
	int		r;

	/* Load 8 blocks (128 bytes) */
	d0 = _mm_loadu_si128((const __m128i *)(in +   0));
	d1 = _mm_loadu_si128((const __m128i *)(in +  AES_BLOCK_SIZE));
	d2 = _mm_loadu_si128((const __m128i *)(in +  AES_BLOCK_SIZE * 2));
	d3 = _mm_loadu_si128((const __m128i *)(in +  AES_BLOCK_SIZE * 3));
	d4 = _mm_loadu_si128((const __m128i *)(in +  AES_BLOCK_SIZE * 4));
	d5 = _mm_loadu_si128((const __m128i *)(in +  AES_BLOCK_SIZE * 5));
	d6 = _mm_loadu_si128((const __m128i *)(in +  AES_BLOCK_SIZE * 6));
	d7 = _mm_loadu_si128((const __m128i *)(in +  AES_BLOCK_SIZE * 7));

	if (encrypt)
	{
		W8(rk);
		for (r = 1; r < nr; r++)
		{
			RE(d0, rk, r); RE(d1, rk, r); RE(d2, rk, r); RE(d3, rk, r);
			RE(d4, rk, r); RE(d5, rk, r); RE(d6, rk, r); RE(d7, rk, r);
		}
		FE(d0, rk, nr); FE(d1, rk, nr); FE(d2, rk, nr); FE(d3, rk, nr);
		FE(d4, rk, nr); FE(d5, rk, nr); FE(d6, rk, nr); FE(d7, rk, nr);
	}
	else
	{
		W8(rk);
		for (r = 1; r < nr; r++)
		{
			RD(d0, rk, r); RD(d1, rk, r); RD(d2, rk, r); RD(d3, rk, r);
			RD(d4, rk, r); RD(d5, rk, r); RD(d6, rk, r); RD(d7, rk, r);
		}
		FD(d0, rk, nr); FD(d1, rk, nr); FD(d2, rk, nr); FD(d3, rk, nr);
		FD(d4, rk, nr); FD(d5, rk, nr); FD(d6, rk, nr); FD(d7, rk, nr);
	}

	/* Store 8 blocks */
	_mm_storeu_si128((__m128i *)(out +   0), d0);
	_mm_storeu_si128((__m128i *)(out +  AES_BLOCK_SIZE), d1);
	_mm_storeu_si128((__m128i *)(out +  AES_BLOCK_SIZE * 2), d2);
	_mm_storeu_si128((__m128i *)(out +  AES_BLOCK_SIZE * 3), d3);
	_mm_storeu_si128((__m128i *)(out +  AES_BLOCK_SIZE * 4), d4);
	_mm_storeu_si128((__m128i *)(out +  AES_BLOCK_SIZE * 5), d5);
	_mm_storeu_si128((__m128i *)(out +  AES_BLOCK_SIZE * 6), d6);
	_mm_storeu_si128((__m128i *)(out +  AES_BLOCK_SIZE * 7), d7);
}

__attribute__((target("aes")))
static void	processSingleBlockGeneric(__m128i		*d,
									  const __m128i	*rk,
									  int			nr,
									  int			encrypt)
{
	int	r;

	if (encrypt)
	{
		W1(*d, rk);
		for (r = 1; r < nr; r++)
			RE(*d, rk, r);
		FE(*d, rk, nr);
	}
	else
	{
		W1(*d, rk);
		for (r = 1; r < nr; r++)
			RD(*d, rk, r);
		FD(*d, rk, nr);
	}
}

__attribute__((target("aes")))
void	aesProcessBlocksX86(const uint8_t			*in,
							  uint8_t				*out,
							  const uint32_t		*roundKeys,
							  size_t				blocks,
							  int					nr,
							  int					encrypt)
{
	__m128i	rk[AES_MAX_ROUNDS + 1];
	__m128i	d;
	size_t	i;

	prepareKeys(rk, roundKeys, nr, encrypt);
	i = 0;
	while (i + 8 <= blocks)
	{
		process8BlocksGeneric(in + i * AES_BLOCK_SIZE, out + i * AES_BLOCK_SIZE, rk, nr, encrypt);
		i += 8;
	}
	while (i < blocks)
	{
		d = _mm_loadu_si128((const __m128i *)(in + i * AES_BLOCK_SIZE));
		processSingleBlockGeneric(&d, rk, nr, encrypt);
		_mm_storeu_si128((__m128i *)(out + i * AES_BLOCK_SIZE), d);
		i++;
	}
}

