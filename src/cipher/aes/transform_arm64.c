/*  ---------- Round primitives - single block ---------- */

/* Middle round: SubBytes + ShiftRows + MixColumns + AddRoundKey */
#define RE(d, rk, r)  (d) = vaesmcq_u8(vaeseq_u8((d), (rk)[r]))
#define RD(d, rk, r)  (d) = vaesimcq_u8(vaesdq_u8((d), (rk)[r]))

/* Final round: SubBytes + ShiftRows + AddRoundKey (no MixColumns) */
#define FE(d, rk, nr) (d) = veorq_u8(vaeseq_u8((d), (rk)[(nr) - 1]), (rk)[nr])
#define FD(d, rk, nr) (d) = veorq_u8(vaesdq_u8((d), (rk)[(nr) - 1]), (rk)[nr])

/**
 * @brief Prepare round keys for AES instructions.
 *
 * The AES instructions expect the round keys in a specific format:
 * - Each round key is loaded as a 128-bit vector, with bytes in reverse order.
 * - For decryption, the middle round keys (1..nr-1) must be transformed with vaesimcq_u8.
 *
 * @param rk Output array of round keys in NEON format (size: AES_MAX_ROUNDS + 1)
 * @param roundKeys Input round keys as generated by the key expansion
 * @param nr Number of rounds (10, 12, or 14)
 * @param encrypt Non-zero for encryption, zero for decryption
 */
__attribute__((target("aes"), always_inline))
static inline void	prepareKeys(uint8x16_t		*rk,
								const uint32_t	*roundKeys,
								int				nr,
								int				encrypt)
{
	uint8x16_t	orig[AES_MAX_ROUNDS + 1];
	int			i;

	for (i = 0; i <= nr; i++)
		orig[i] = vrev32q_u8(vld1q_u8((const uint8_t *)&roundKeys[i * 4]));
	if (encrypt)
	{
		for (i = 0; i <= nr; i++)
			rk[i] = orig[i];
	}
	else
	{
		rk[0] = orig[nr];
		for (i = 1; i < nr; i++)
			rk[i] = vaesimcq_u8(orig[nr - i]);
		rk[nr] = orig[0];
	}
}

