/* ---------- Round primitives - 8 blocks in parallel ---------- */

#define R8E(rk, r) \
	RE(d0, rk, r); RE(d1, rk, r); RE(d2, rk, r); RE(d3, rk, r); \
	RE(d4, rk, r); RE(d5, rk, r); RE(d6, rk, r); RE(d7, rk, r)

#define R8D(rk, r) \
	RD(d0, rk, r); RD(d1, rk, r); RD(d2, rk, r); RD(d3, rk, r); \
	RD(d4, rk, r); RD(d5, rk, r); RD(d6, rk, r); RD(d7, rk, r)

#define F8E(rk, nr) \
	FE(d0, rk, nr); FE(d1, rk, nr); FE(d2, rk, nr); FE(d3, rk, nr); \
	FE(d4, rk, nr); FE(d5, rk, nr); FE(d6, rk, nr); FE(d7, rk, nr)

#define F8D(rk, nr) \
	FD(d0, rk, nr); FD(d1, rk, nr); FD(d2, rk, nr); FD(d3, rk, nr); \
	FD(d4, rk, nr); FD(d5, rk, nr); FD(d6, rk, nr); FD(d7, rk, nr)

/* ---------- Fully unrolled round sequences per key size ---------- */

/* AES-128 : nr=10 - 9 middle rounds (0..8) + final */
#define UNROLL1_ENC_10(d, rk) \
	RE(d,rk,0); RE(d,rk,1); RE(d,rk,2); RE(d,rk,3); RE(d,rk,4); \
	RE(d,rk,5); RE(d,rk,6); RE(d,rk,7); RE(d,rk,8); FE(d,rk,10)

#define UNROLL1_DEC_10(d, rk) \
	RD(d,rk,0); RD(d,rk,1); RD(d,rk,2); RD(d,rk,3); RD(d,rk,4); \
	RD(d,rk,5); RD(d,rk,6); RD(d,rk,7); RD(d,rk,8); FD(d,rk,10)

#define UNROLL8_ENC_10(rk) \
	R8E(rk,0); R8E(rk,1); R8E(rk,2); R8E(rk,3); R8E(rk,4); \
	R8E(rk,5); R8E(rk,6); R8E(rk,7); R8E(rk,8); F8E(rk,10)

#define UNROLL8_DEC_10(rk) \
	R8D(rk,0); R8D(rk,1); R8D(rk,2); R8D(rk,3); R8D(rk,4); \
	R8D(rk,5); R8D(rk,6); R8D(rk,7); R8D(rk,8); F8D(rk,10)

/* AES-192 : nr=12 - 11 middle rounds (0..10) + final */
#define UNROLL1_ENC_12(d, rk) \
	RE(d,rk,0); RE(d,rk,1); RE(d,rk,2);  RE(d,rk,3);  RE(d,rk,4); \
	RE(d,rk,5); RE(d,rk,6); RE(d,rk,7);  RE(d,rk,8);  RE(d,rk,9); \
	RE(d,rk,10); FE(d,rk,12)

