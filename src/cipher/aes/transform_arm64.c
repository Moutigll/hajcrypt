/* ---------- Small: generic 8-block function, loop not unrolled ---------- */

__attribute__((target("aes")))
static void	process8BlocksGeneric(const uint8_t		*in,
								  uint8_t			*out,
								  const uint8x16_t	*rk,
								  int				nr,
								  int				encrypt)
{
	uint8x16_t	d0, d1, d2, d3, d4, d5, d6, d7;
	int			r;

	d0 = vld1q_u8(in +   0);					d1 = vld1q_u8(in +  AES_BLOCK_SIZE);
	d2 = vld1q_u8(in +  AES_BLOCK_SIZE * 2);	d3 = vld1q_u8(in +  AES_BLOCK_SIZE * 3);
	d4 = vld1q_u8(in +  AES_BLOCK_SIZE * 4);	d5 = vld1q_u8(in +  AES_BLOCK_SIZE * 5);
	d6 = vld1q_u8(in +  AES_BLOCK_SIZE * 6);	d7 = vld1q_u8(in +  AES_BLOCK_SIZE * 7);
	if (encrypt)
	{
		for (r = 0; r < nr - 1; r++)
		{
			RE(d0, rk, r); RE(d1, rk, r); RE(d2, rk, r); RE(d3, rk, r);
			RE(d4, rk, r); RE(d5, rk, r); RE(d6, rk, r); RE(d7, rk, r);
		}
		FE(d0, rk, nr); FE(d1, rk, nr); FE(d2, rk, nr); FE(d3, rk, nr);
		FE(d4, rk, nr); FE(d5, rk, nr); FE(d6, rk, nr); FE(d7, rk, nr);
	}
	else
	{
		for (r = 0; r < nr - 1; r++)
		{
			RD(d0, rk, r); RD(d1, rk, r); RD(d2, rk, r); RD(d3, rk, r);
			RD(d4, rk, r); RD(d5, rk, r); RD(d6, rk, r); RD(d7, rk, r);
		}
		FD(d0, rk, nr); FD(d1, rk, nr); FD(d2, rk, nr); FD(d3, rk, nr);
		FD(d4, rk, nr); FD(d5, rk, nr); FD(d6, rk, nr); FD(d7, rk, nr);
	}
	vst1q_u8(out +   0, d0);					vst1q_u8(out +  AES_BLOCK_SIZE, d1);
	vst1q_u8(out +  AES_BLOCK_SIZE * 2, d2);	vst1q_u8(out +  AES_BLOCK_SIZE * 3, d3);
	vst1q_u8(out +  AES_BLOCK_SIZE * 4, d4);	vst1q_u8(out +  AES_BLOCK_SIZE * 5, d5);
	vst1q_u8(out +  AES_BLOCK_SIZE * 6, d6);	vst1q_u8(out +  AES_BLOCK_SIZE * 7, d7);
}

__attribute__((target("aes")))
static void	processSingleBlockGeneric(uint8x16_t		*d,
									  const uint8x16_t	*rk,
									  int				nr,
									  int				encrypt)
{
	int	r;

	if (encrypt)
	{
		for (r = 0; r < nr - 1; r++)
			RE(*d, rk, r);
		FE(*d, rk, nr);
	}
	else
	{
		for (r = 0; r < nr - 1; r++)
			RD(*d, rk, r);
		FD(*d, rk, nr);
	}
}

__attribute__((target("aes")))
void	aesProcessBlocksNeon(const uint8_t			*in,
								  uint8_t			*out,
								  const uint32_t	*roundKeys,
								  size_t			blocks,
								  int				nr,
								  int				encrypt)
{
	uint8x16_t	rk[AES_MAX_ROUNDS + 1];
	uint8x16_t	d;
	size_t		i;

	prepareKeys(rk, roundKeys, nr, encrypt);
	i = 0;
	while (i + 8 <= blocks)
	{
		process8BlocksGeneric(in + i * AES_BLOCK_SIZE, out + i * AES_BLOCK_SIZE, rk, nr, encrypt);
		i += 8;
	}
	while (i < blocks)
	{
		d = vld1q_u8(in + i * AES_BLOCK_SIZE);
		processSingleBlockGeneric(&d, rk, nr, encrypt);
		vst1q_u8(out + i * AES_BLOCK_SIZE, d);
		i++;
	}
}

